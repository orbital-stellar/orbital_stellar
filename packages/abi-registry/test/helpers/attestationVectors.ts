/**
 * Builds `test-vectors/attestation-v1.json`: the language-neutral conformance
 * suite for the attestation envelope (SEP §5). A verifier written in any
 * language passes if, for every entry, it reaches the same verdict.
 *
 * The file is generated, never hand-edited: `scripts/generate-attestation-vectors.ts`
 * writes it, and `test/attestationVectors.test.ts` fails if it drifts from
 * what this function produces. ed25519 signatures are deterministic, so the
 * output is stable.
 *
 * The seeds below are published test keys. They protect nothing.
 */
import { createHash } from "node:crypto";
import { Keypair } from "@stellar/stellar-sdk";
import {
  ATTESTATION_DOMAIN,
  SEP53_MESSAGE_PREFIX,
  attestationSigningMessage,
  signAttestation,
} from "../../src/attestation.js";
import { canonicalizeJson } from "../../src/canonicalJson.js";
import type { AttestationDocument } from "../../src/types.js";

const CONTRACT_ID = "CCW67TSZV3SSS2HXMBQ5JFGCKJNXKZM7UQUWUZPUTHXSTZLEO7SJMI75";
const WASM_HASH = "0123456789abcdef".repeat(4);
const NOW = "2026-06-01T00:00:00Z";
const OTHER_DOMAIN = "orbital-computation-attestation-v1";

function keypair(byte: number): Keypair {
  return Keypair.fromRawEd25519Seed(Buffer.alloc(32, byte));
}

const ALICE = keypair(1);
const BOB = keypair(2);

const TRANSFER = {
  name: "transfer",
  topics: [
    { name: "from", type: "address" },
    { name: "to", type: "address" },
  ],
  data: [{ name: "amount", type: "i128" }],
};

function wasmDocument(overrides: Record<string, unknown> = {}): AttestationDocument {
  return {
    contractId: CONTRACT_ID,
    executableKind: "wasm",
    wasmHash: WASM_HASH,
    events: [TRANSFER],
    attester: ALICE.publicKey(),
    createdAt: "2026-01-01T00:00:00Z",
    ...overrides,
  } as AttestationDocument;
}

type Expected = { status: "valid" } | { status: "invalid"; code: string };

type VectorOptions = {
  domain?: string;
  now?: string;
  expectedWasmHash?: string;
  checkExpiry?: boolean;
};

type EnvelopeVector = {
  name: string;
  options: VectorOptions;
  envelope: unknown;
  /** Present when the envelope was signed; lets an implementer check each step. */
  signing?: { message: string; digestHex: string };
  expected: Expected;
};

function sha256Hex(text: string): string {
  return createHash("sha256").update(Buffer.from(text, "utf8")).digest("hex");
}

function signingTrace(document: { attester: string }, domain: string) {
  const message = attestationSigningMessage(document, domain);
  return { message, digestHex: sha256Hex(SEP53_MESSAGE_PREFIX + message) };
}

function valid(
  name: string,
  document: { attester: string },
  signer: Keypair,
  options: VectorOptions = {},
): EnvelopeVector {
  const domain = options.domain ?? ATTESTATION_DOMAIN;
  return {
    name,
    options,
    envelope: signAttestation(document, signer.secret(), { domain }),
    signing: signingTrace(document, domain),
    expected: { status: "valid" },
  };
}

function invalid(
  name: string,
  code: string,
  envelope: unknown,
  options: VectorOptions = {},
): EnvelopeVector {
  return { name, options, envelope, expected: { status: "invalid", code } };
}

function canonicalCase(name: string, input: unknown) {
  return { name, input, canonical: canonicalizeJson(input) };
}

export function buildAttestationVectors() {
  const base = signAttestation(wasmDocument(), ALICE.secret());

  // Same document with its members written in reverse order: a verifier must
  // canonicalize rather than hash the bytes as received.
  const reversedPayload = Object.fromEntries(Object.entries(base.payload).reverse());
  const reordered = { ...base, payload: reversedPayload };

  // Event-schema documents only carry identifiers, so non-ASCII text can only
  // appear in a payload of another shape. The envelope is generic over its
  // payload, so exercise it with a computation-result document, which has
  // free-form text, under that document kind's own domain.
  const unicodeDocument = {
    attester: ALICE.publicKey(),
    workerId: "w1",
    windowId: "w1:c:1",
    conditionId: "oracle",
    observedAt: "2026-01-01T00:00:00Z",
    result: { memo: "caf\u00e9 <&> \u2028 \u{1f680}", count: 7 },
    resultHash: "a".repeat(64),
  };

  const sacDocument = wasmDocument({ executableKind: "stellarAsset", wasmHash: undefined });

  return {
    $comment:
      "Generated by scripts/generate-attestation-vectors.ts from test/helpers/attestationVectors.ts. Do not edit. Seeds are public test keys.",
    version: 1,
    domain: ATTESTATION_DOMAIN,
    sep53Prefix: SEP53_MESSAGE_PREFIX,
    keys: {
      alice: { seedHex: "01".repeat(32), address: ALICE.publicKey() },
      bob: { seedHex: "02".repeat(32), address: BOB.publicKey() },
    },
    canonicalization: [
      canonicalCase("empty object", {}),
      canonicalCase("empty array", []),
      canonicalCase("literals", [null, true, false]),
      canonicalCase("integers", [0, -1, 42, 4294967295, 9007199254740991]),
      canonicalCase("members sorted at every depth", { b: { z: 1, a: [{ y: 1, x: 2 }] }, a: 0 }),
      canonicalCase("array order is kept", [3, 1, 2]),
      canonicalCase("keys sort by UTF-16 code unit, not code point", {
        "～": 1,
        "\u{10000}": 2,
        é: 3,
        e: 4,
      }),
      canonicalCase("only quote, backslash and control characters are escaped", {
        s: 'q"b\\n\n\r\t\b\f\u0001\u001f<>&/\u007f  ',
      }),
      canonicalCase("non-ASCII is written as UTF-8, not \\u escapes", "café \u{1f680}"),
    ],
    envelopes: [
      valid("wasm attestation", wasmDocument(), ALICE),
      valid("stellar asset attestation (no wasmHash)", sacDocument, ALICE),
      valid("non-ASCII text in a payload of another shape", unicodeDocument, ALICE, {
        domain: OTHER_DOMAIN,
      }),
      valid("with a future expiry", wasmDocument({ expiresAt: "2026-07-01T00:00:00Z" }), ALICE, {
        now: NOW,
      }),
      valid(
        "supersedes another attestation",
        wasmDocument({ supersedes: "f".repeat(64), createdAt: "2026-02-01T00:00:00Z" }),
        ALICE,
      ),
      valid("signed by a different attester", wasmDocument({ attester: BOB.publicKey() }), BOB),
      valid("signed under another domain", wasmDocument(), ALICE, { domain: OTHER_DOMAIN }),
      valid("expected wasm hash matches (case-insensitive)", wasmDocument(), ALICE, {
        expectedWasmHash: WASM_HASH.toUpperCase(),
      }),
      {
        name: "payload members in a different order than canonical",
        options: {},
        envelope: reordered,
        signing: signingTrace(wasmDocument(), ATTESTATION_DOMAIN),
        expected: { status: "valid" },
      } satisfies EnvelopeVector,
      invalid("tampered payload", "bad-signature", {
        ...base,
        payload: { ...base.payload, createdAt: "2026-01-02T00:00:00Z" },
      }),
      invalid("verified under the wrong domain", "bad-signature", base, { domain: OTHER_DOMAIN }),
      invalid("signature from a different key", "bad-signature", {
        ...base,
        signature: signAttestation(wasmDocument({ attester: BOB.publicKey() }), BOB.secret())
          .signature,
      }),
      invalid("signature is not base64 of 64 bytes", "bad-signature", {
        ...base,
        signature: "AAAA",
      }),
      invalid("pre-v1 envelope without a version", "unsupported-version", {
        payload: base.payload,
        publicKey: base.publicKey,
        signature: base.signature,
      }),
      invalid("unknown envelope version", "unsupported-version", { ...base, v: 2 }),
      invalid("publicKey is not an account address", "bad-public-key", {
        ...base,
        publicKey: "not-an-address",
      }),
      invalid("publicKey differs from payload.attester", "attester-mismatch", {
        ...base,
        publicKey: BOB.publicKey(),
      }),
      invalid(
        "expired",
        "expired",
        signAttestation(wasmDocument({ expiresAt: "2026-05-01T00:00:00Z" }), ALICE.secret()),
        { now: NOW },
      ),
      invalid(
        "expires exactly now",
        "expired",
        signAttestation(wasmDocument({ expiresAt: NOW }), ALICE.secret()),
        { now: NOW },
      ),
      invalid(
        "expiresAt is not a timestamp",
        "malformed-expiry",
        signAttestation(wasmDocument({ expiresAt: "next tuesday" }), ALICE.secret()),
        { now: NOW },
      ),
      valid(
        "expired but expiry checking is off",
        wasmDocument({ expiresAt: "2026-05-01T00:00:00Z" }),
        ALICE,
        { now: NOW, checkExpiry: false },
      ),
      invalid(
        "expiresAt is a date with no time or offset",
        "malformed-expiry",
        signAttestation(wasmDocument({ expiresAt: "2026-07-01" }), ALICE.secret()),
        { now: NOW },
      ),
      invalid("expected wasm hash differs", "wasm-hash-mismatch", base, {
        expectedWasmHash: "b".repeat(64),
      }),
      invalid(
        "wasm hash expected of a stellar asset attestation",
        "not-a-wasm-attestation",
        signAttestation(sacDocument, ALICE.secret()),
        { expectedWasmHash: WASM_HASH },
      ),
    ] satisfies EnvelopeVector[],
  };
}
